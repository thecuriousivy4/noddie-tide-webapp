// Server-side document generation. Every instrument the register issues is a real PDF,
// produced here with pdf-lib (no headless browser), hashed with SHA-256, and stored with
// its hash in the transparency log. The hash is what "proof of notice served" means.
//
// All content is synthetic and each document says so on its face.

import "server-only";
import { createHash } from "node:crypto";
import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import type { ChangeRequestFull, ProofChain } from "@/lib/registry/changes";

const OCHRE = rgb(0.604, 0.29, 0.141);
const GOLD = rgb(0.662, 0.502, 0.184);
const INK = rgb(0.114, 0.11, 0.102);
const INK2 = rgb(0.361, 0.353, 0.333);
const LINE = rgb(0.804, 0.776, 0.71);
const RED = rgb(0.639, 0.227, 0.173);
const GREEN = rgb(0.184, 0.42, 0.29);

const A4 = { w: 595.28, h: 841.89 };
const M = 56;

interface Fonts {
  reg: PDFFont;
  bold: PDFFont;
  ital: PDFFont;
  mono: PDFFont;
}

export interface Instrument {
  filename: string;
  bytes: Uint8Array;
  sha256: string;
}

const SYNTH_NOTE =
  "Synthetic document generated by the Noddie prototype. All names, places, people and data are fictional. Not a legal instrument. Real use would require co-design led by Traditional Owners, under their governance and the CARE Principles for Indigenous Data Governance.";

async function start(opts: {
  title: string;
  accent: ReturnType<typeof rgb>;
  refNo: string;
  /** The corporation whose instrument this is. Printed as the masthead. */
  authority: string;
  /** How this document relates to that authority, e.g. "served on the corporation". */
  issuer: string;
  dateISO: string;
}) {
  const doc = await PDFDocument.create();
  doc.setTitle(`${opts.title} — ${opts.refNo}`);
  doc.setProducer("Noddie (prototype)");
  doc.setCreationDate(new Date(opts.dateISO));
  const page = doc.addPage([A4.w, A4.h]);
  const fonts: Fonts = {
    reg: await doc.embedFont(StandardFonts.TimesRoman),
    bold: await doc.embedFont(StandardFonts.TimesRomanBold),
    ital: await doc.embedFont(StandardFonts.TimesRomanItalic),
    mono: await doc.embedFont(StandardFonts.Courier),
  };

  let y = A4.h - M;

  // Neutral lozenge mark: a ring over a ridgeline. Not a crest, not a cultural motif.
  const cx = M + 16;
  const cy = y - 6;
  page.drawCircle({ x: cx, y: cy, size: 16, borderColor: opts.accent, borderWidth: 1.2 });
  page.drawLine({ start: { x: cx - 10, y: cy - 2 }, end: { x: cx - 3, y: cy + 4 }, thickness: 1, color: opts.accent });
  page.drawLine({ start: { x: cx - 3, y: cy + 4 }, end: { x: cx + 3, y: cy - 1 }, thickness: 1, color: opts.accent });
  page.drawLine({ start: { x: cx + 3, y: cy - 1 }, end: { x: cx + 10, y: cy + 3 }, thickness: 1, color: opts.accent });

  // The corporation is the authority on the instrument. Noddie is only the register it was
  // issued through, and the document states it in that order — a community's consent is not
  // the software's to claim.
  page.drawText(opts.authority.toUpperCase(), {
    x: cx + 26,
    y: cy + 2,
    size: 12,
    font: fonts.bold,
    color: INK,
  });
  page.drawText(`Issued through the Noddie heritage register · ${opts.issuer}`, {
    x: cx + 26,
    y: cy - 10,
    size: 8.5,
    font: fonts.reg,
    color: INK2,
  });

  y = cy - 30;
  page.drawLine({ start: { x: M, y }, end: { x: A4.w - M, y }, thickness: 1, color: opts.accent });
  y -= 30;

  page.drawText(opts.title.toUpperCase(), { x: M, y, size: 17, font: fonts.bold, color: INK });
  y -= 16;
  page.drawText(`Reference ${opts.refNo}   ·   Issued ${fmtDate(opts.dateISO)}`, {
    x: M,
    y,
    size: 9.5,
    font: fonts.mono,
    color: INK2,
  });
  y -= 24;

  return { doc, page, fonts, y };
}

function fmtDate(iso: string): string {
  const d = new Date(iso);
  if (isNaN(d.getTime())) return iso;
  return d.toLocaleDateString("en-AU", { day: "2-digit", month: "long", year: "numeric" });
}

function fmtDateTime(value: Date | string | null | undefined): string {
  if (!value) return "—";
  const d = typeof value === "string" ? new Date(value) : value;
  return d.toLocaleString("en-AU", { dateStyle: "medium", timeStyle: "short" });
}

function wrap(text: string, font: PDFFont, size: number, maxWidth: number): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    const trial = line ? `${line} ${w}` : w;
    if (font.widthOfTextAtSize(trial, size) > maxWidth && line) {
      lines.push(line);
      line = w;
    } else {
      line = trial;
    }
  }
  if (line) lines.push(line);
  return lines.length ? lines : [""];
}

function field(
  page: PDFPage,
  fonts: Fonts,
  y: number,
  label: string,
  value: string,
  opts: { mono?: boolean; x?: number; width?: number } = {},
): number {
  const x = opts.x ?? M;
  const width = opts.width ?? A4.w - 2 * M;
  page.drawText(label.toUpperCase(), { x, y, size: 7.5, font: fonts.bold, color: INK2 });
  y -= 13;
  const font = opts.mono ? fonts.mono : fonts.reg;
  const size = opts.mono ? 8.5 : 11;
  for (const ln of wrap(value, font, size, width)) {
    page.drawText(ln, { x, y, size, font, color: INK });
    y -= size + 4;
  }
  return y - 8;
}

function paragraph(page: PDFPage, fonts: Fonts, y: number, text: string, size = 10.5): number {
  for (const ln of wrap(text, fonts.reg, size, A4.w - 2 * M)) {
    page.drawText(ln, { x: M, y, size, font: fonts.reg, color: INK });
    y -= size + 4.5;
  }
  return y - 10;
}

function statusBox(page: PDFPage, fonts: Fonts, y: number, label: string, color: ReturnType<typeof rgb>): number {
  const h = 30;
  page.drawRectangle({
    x: M,
    y: y - h,
    width: A4.w - 2 * M,
    height: h,
    borderColor: color,
    borderWidth: 1.2,
    color: rgb(1, 1, 1),
  });
  page.drawText(label, { x: M + 14, y: y - h + 10, size: 12, font: fonts.bold, color });
  return y - h - 18;
}

function rule(page: PDFPage, y: number): number {
  page.drawLine({ start: { x: M, y }, end: { x: A4.w - M, y }, thickness: 0.75, color: LINE });
  return y - 18;
}

function footer(page: PDFPage, fonts: Fonts, note: string) {
  const y = M - 14;
  page.drawLine({ start: { x: M, y: y + 16 }, end: { x: A4.w - M, y: y + 16 }, thickness: 0.75, color: LINE });
  let yy = y + 4;
  for (const ln of wrap(note, fonts.ital, 8, A4.w - 2 * M)) {
    page.drawText(ln, { x: M, y: yy, size: 8, font: fonts.ital, color: INK2 });
    yy -= 10;
  }
}

async function finish(doc: PDFDocument, filename: string): Promise<Instrument> {
  const bytes = await doc.save();
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  return { filename, bytes, sha256 };
}

/** The place is identified by its public reference only. Protected fields are never read. */
function placeLines(cr: ChangeRequestFull): string {
  return `${cr.place.publicRef} — ${cr.place.publicName} (${cr.place.country}). Generalized zones ${cr.place.zoneCells.join(", ")}. Positions indicative only.`;
}

/**
 * Proof of notice. Issued at the moment a request leaves DRAFT, so the community is
 * served before it is asked to decide — and so the hash predates every approval.
 */
export async function buildWorksNotice(cr: ChangeRequestFull): Promise<Instrument> {
  const ministerial = cr.initiatorRole === "minister";
  const { doc, page, fonts, y: y0 } = await start({
    title: ministerial ? "Ministerial announcement of proposed works" : "Notice of proposed works",
    accent: OCHRE,
    refNo: cr.ref,
    authority: cr.custodianOrg.name,
    issuer: `served on the corporation in respect of ${cr.place.publicRef}`,
    dateISO: new Date().toISOString(),
  });
  let y = y0;

  y = statusBox(page, fonts, y, "NOTICE SERVED — NO AUTHORITY CONFERRED", OCHRE);

  y = paragraph(
    page,
    fonts,
    y,
    ministerial
      ? "This announcement records that a Minister has proposed works affecting a place on the register. It is a notice only. It does not authorise any works, and the Minister's consent is not a consent of the Traditional Owners."
      : "This notice records that a proponent has proposed works affecting a place on the register. It is a notice only. It confers no authority to enter, disturb or carry out works on the place.",
  );

  y = field(page, fonts, y, "Place affected", placeLines(cr));
  y = field(page, fonts, y, "Proposal", `${cr.title}. ${cr.description}`);
  y = field(page, fonts, y, "Lodged by", `${cr.initiatorName} (acting as ${cr.initiatorRole})`);
  y = field(page, fonts, y, "Permit sought for", `${cr.subjectName} — role ${cr.grantedRole}`);
  y = rule(page, y);
  y = field(
    page,
    fonts,
    y,
    "Routed to",
    `${cr.custodianOrg.name}. Consent rule: ${cr.custodianOrg.consentRule}. Contact ${cr.custodianOrg.contact}.`,
  );
  y = field(
    page,
    fonts,
    y,
    "What happens next",
    `The request is now open to the custodian quorum. It can only proceed if at least ${cr.quorumThreshold} of ${cr.custodianOrg.custodianCount} custodians independently approve it. No other party — including a Minister, a platform administrator or the operator of this register — can grant it.`,
  );
  y = field(
    page,
    fonts,
    y,
    "Protected details",
    "The recorded name, boundary and cultural significance of the place are held encrypted and were not read in the preparation of this notice. They are not available to the proponent, to a Minister, or to this register's operator.",
  );

  footer(page, fonts, SYNTH_NOTE);
  return finish(doc, `${cr.ref}-notice.pdf`);
}

/** Proof of authority, issued only after a quorum commits. Lists the whole chain. */
export async function buildPermitInstrument(
  cr: ChangeRequestFull,
  proofs: ProofChain,
): Promise<Instrument> {
  const { doc, page, fonts, y: y0 } = await start({
    title: "Instrument of consent — works permit",
    accent: GOLD,
    refNo: cr.ref,
    authority: cr.custodianOrg.name,
    issuer: "granted by the custodians of the corporation",
    dateISO: (cr.committedAt ?? new Date()).toISOString(),
  });
  let y = y0;

  y = statusBox(page, fonts, y, "GRANTED BY CUSTODIAN QUORUM", GREEN);

  y = paragraph(
    page,
    fonts,
    y,
    `The custodians named below have consented to the works described in ${cr.ref}. This instrument is evidence of that consent. It is effective only while the role ${cr.grantedRole} appears in a network-signed access token held by the permit holder; it cannot be made effective by this register, by a Minister, or by any administrator.`,
  );

  y = field(page, fonts, y, "Permit holder", `${cr.subjectName} — role ${cr.grantedRole}`);
  y = field(page, fonts, y, "Place affected", placeLines(cr));
  y = field(page, fonts, y, "Works consented to", `${cr.title}. ${cr.description}`);
  y = rule(page, y);

  y = field(
    page,
    fonts,
    y,
    "Proof of notice",
    proofs.notice.present
      ? `${proofs.notice.filename ?? "notice.pdf"} served ${fmtDateTime(proofs.notice.issuedAt)}`
      : "NOT PRESENT",
  );
  y = field(page, fonts, y, "Notice SHA-256", proofs.notice.sha256 ?? "—", { mono: true });

  page.drawText(
    `PROOF OF CONSENT — ${proofs.consent.signatures.length} OF ${cr.custodianOrg.custodianCount} CUSTODIANS, THRESHOLD ${proofs.consent.threshold}`,
    { x: M, y, size: 7.5, font: fonts.bold, color: INK2 },
  );
  y -= 15;
  for (const s of proofs.consent.signatures) {
    page.drawText(`${s.custodian}`, { x: M, y, size: 11, font: fonts.reg, color: INK });
    page.drawText(fmtDateTime(s.at), { x: M + 190, y, size: 9, font: fonts.reg, color: INK2 });
    page.drawText(s.signatureRef, { x: M + 300, y, size: 8, font: fonts.mono, color: INK2 });
    y -= 15;
  }
  y -= 8;

  y = field(page, fonts, y, "Proof of authority — network grant", proofs.authority.tideGrantRef ?? "—", {
    mono: true,
  });
  y = field(
    page,
    fonts,
    y,
    "Ministerial consent",
    proofs.ministerConsent.recorded
      ? `Recorded ${proofs.ministerConsent.by ? `by ${proofs.ministerConsent.by}` : ""} — not counted toward the quorum, and not required for this grant.`
      : "Not recorded. Not required.",
  );

  footer(page, fonts, SYNTH_NOTE);
  return finish(doc, `${cr.ref}-permit.pdf`);
}

export async function buildRefusalNotice(cr: ChangeRequestFull): Promise<Instrument> {
  const { doc, page, fonts, y: y0 } = await start({
    title: "Notice of refusal",
    accent: RED,
    refNo: cr.ref,
    authority: cr.custodianOrg.name,
    issuer: "decision of the custodians of the corporation",
    dateISO: (cr.decidedAt ?? new Date()).toISOString(),
  });
  let y = y0;

  y = statusBox(page, fonts, y, "REFUSED — NO PERMIT EXISTS", RED);
  y = paragraph(
    page,
    fonts,
    y,
    `The custodians have declined the works described in ${cr.ref}. No permit role was created, and no further step in this register can create one. A fresh request would start again at notice.`,
  );
  y = field(page, fonts, y, "Place affected", placeLines(cr));
  y = field(page, fonts, y, "Request", `${cr.title}. ${cr.description}`);
  y = field(page, fonts, y, "Reason given", cr.rejectionReason ?? "No reason recorded.");
  y = field(page, fonts, y, "Decided", fmtDateTime(cr.decidedAt));
  footer(page, fonts, SYNTH_NOTE);
  return finish(doc, `${cr.ref}-refusal.pdf`);
}

/** Receipt for a works notice lodged against a live permit, quoting the verified token. */
export async function buildLodgementReceipt(input: {
  ref: string;
  /** The corporation that holds the place these works were lodged against. */
  authority: string;
  placeRef: string;
  placeName: string;
  holderName: string;
  outcome: "accepted" | "refused";
  reason: string;
  tokenIss: string;
  tokenSub: string;
  tokenRoles: string[];
  verifiedVia: string;
  at: string;
}): Promise<Instrument> {
  const accepted = input.outcome === "accepted";
  const { doc, page, fonts, y: y0 } = await start({
    title: "Works notice — lodgement receipt",
    accent: accepted ? GOLD : RED,
    refNo: input.ref,
    authority: input.authority,
    issuer: `lodgement against ${input.placeRef}`,
    dateISO: input.at,
  });
  let y = y0;

  y = statusBox(
    page,
    fonts,
    y,
    accepted ? "ACCEPTED — PERMIT ROLE PRESENT IN TOKEN" : "REFUSED — NO PERMIT ROLE IN TOKEN",
    accepted ? GREEN : RED,
  );
  y = field(page, fonts, y, "Place", `${input.placeRef} — ${input.placeName}`);
  y = field(page, fonts, y, "Lodged by", input.holderName);
  y = field(page, fonts, y, "Outcome", input.reason);
  y = rule(page, y);
  y = paragraph(
    page,
    fonts,
    y,
    "The decision above was taken from the access token presented with the request, after verifying its signature. It was not read from any column in this register's database.",
  );
  y = field(page, fonts, y, "Token issuer", input.tokenIss, { mono: true });
  y = field(page, fonts, y, "Token subject", input.tokenSub, { mono: true });
  y = field(page, fonts, y, "Roles in token", input.tokenRoles.join(", ") || "(none)", { mono: true });
  y = field(page, fonts, y, "Verified via", input.verifiedVia, { mono: true });

  footer(page, fonts, SYNTH_NOTE);
  return finish(doc, `${input.ref}-receipt.pdf`);
}
